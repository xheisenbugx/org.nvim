local elines = require("org.element_lines")

describe("org.element_lines", function()
  it("keeps affiliated keyword tables consistent", function()
    for k, official in pairs(elines.AFFILIATED_MAP) do
      eq(true, elines.AFFILIATED[k])
      if k ~= official then
        eq(official, elines.TRANSLATION[k])
      else
        eq(nil, elines.TRANSLATION[k])
      end
    end
    eq("NAME", elines.TRANSLATION.TBLNAME)
    eq("RESULTS", elines.TRANSLATION.RESULT)
    eq("HEADER", elines.TRANSLATION.HEADERS)
    eq(true, elines.DUAL.CAPTION)
    eq(true, elines.DUAL.RESULTS)
    eq(true, elines.MULTIPLE.HEADER)
    eq(true, elines.PARSED.CAPTION)
  end)

  it("classifies Org structural lines", function()
    eq(2, elines.headline_stars("** Heading"))
    eq(nil, elines.headline_stars("**NotHeading"))
    eq(true, elines.is_comment_line("  # note"))
    eq(true, elines.is_comment_line("#"))
    eq(false, elines.is_comment_line("#+TITLE: Foo"))
    eq("LOGBOOK", elines.drawer_name("  :LOGBOOK:  "))
    eq(nil, elines.drawer_name(":bad name:"))
    eq(true, elines.is_end_line("  :End:"))
    eq(false, elines.is_end_line(":END: extra"))
    eq("src", elines.block_type("#+BEGIN_src lua"))
    eq(true, elines.is_dynamic_block("#+BEGIN: clocktable"))
    eq(false, elines.is_dynamic_block("#+BEGIN:"))
    eq(true, elines.is_fixed_width("  : code"))
    eq(true, elines.is_fixed_width(":"))
    eq(false, elines.is_fixed_width(":drawer:"))
    eq(true, elines.is_footnote_def("[fn:1] note"))
    eq(false, elines.is_footnote_def(" [fn:1] indented"))
    eq(true, elines.is_hr("-----"))
    eq(false, elines.is_hr("----"))
    eq("equation*", elines.latex_env_begin("  \\begin{equation*}"))
    eq(true, elines.is_table_line("  | a | b |"))
    eq(false, elines.is_table_line("plain | text"))
  end)

  it("parses property lines and property drawers", function()
    local k, v = elines.property_line("  :Effort:  1:30  ")
    eq("Effort", k)
    eq("1:30", v)
    local k2, v2 = elines.property_line(":EMPTY:")
    eq("EMPTY", k2)
    eq("", v2)
    local lines = { ":PROPERTIES:", ":ID: abc", ":END:", "body" }
    eq(3, elines.property_drawer_end(lines, 1, #lines))
    eq(nil, elines.property_drawer_end({ ":PROPERTIES:", "not a prop", ":END:" }, 1, 3))
  end)
end)
