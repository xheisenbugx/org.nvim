-- Calc in table formulas: symbolic algebra, vectors and matrices, modulo
-- forms and more units. Every expected value is the output of Emacs 31
-- Calc (calc-eval with org-calc-default-modes) or of Org 9.8.10
-- org-table-recalculate.
local calc = require("org.table.calc")
local tbl = require("org.table")

local function recalc(input)
  local buf = org_buffer(input, { 1, 0 })
  tbl.recalc(buf, 1)
  return buf_lines(buf)
end

local function check(cases)
  local bad = {}
  for _, c in ipairs(cases) do
    local okc, got = pcall(calc.eval, c[1])
    if not okc or got ~= c[2] then
      bad[#bad + 1] = string.format("%s: expected %s, got %s", c[1], c[2], tostring(got))
    end
  end
  eq({}, bad)
end

