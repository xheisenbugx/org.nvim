-- Generated from cases run through Emacs Org 9.8.10 (org-table-recalculate t);
-- every expected table is Emacs' output.
local tbl = require("org.table")

local function recalc(input)
  local buf = org_buffer(input, { 1, 0 })
  local l = 1
  for i, s in ipairs(input) do
    if s:match("^%s*#%+TBLFM") then
      l = i - 1
      break
    end
  end
  tbl.recalc(buf, l)
  return buf_lines(buf)
end

