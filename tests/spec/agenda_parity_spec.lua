describe("agenda parity with Emacs", function()
  local dir = vim.fn.tempname()
  vim.fn.mkdir(dir, "p")
  local view = require("org.agenda.view")
  local saved_today, saved_today_days, saved_now
  local saved_agenda
  before_each(function()
    saved_today, saved_today_days, saved_now = date.today, date.today_days, date.now
    local T = date.days_from_civil(2026, 9, 25)
    date.today_days = function()
      return T
    end
    date.today = function()
      return date.from_days(T)
    end
    date.now = function()
      return date.from_days(T, { hour = 14, min = 53 })
    end
    saved_agenda = vim.deepcopy(config.opts.agenda)
    local a = config.opts.agenda
    a.time_grid.separator = "......"
    a.time_grid.time_string = "----------------"
    a.show_current_time_in_grid = false
    a.block_separator = "="
  end)
  after_each(function()
    date.today, date.today_days, date.now = saved_today, saved_today_days, saved_now
    config.opts.agenda = saved_agenda
  end)

  for _, case in ipairs(CASES) do
    it(case.name, function()
      local path = dir .. "/" .. case.fixture
      utils.writefile(path, vim.split(FIXTURES[case.fixture], "\n", { plain = true }))
      require("org.files").invalidate(path)
      config.opts.agenda_files = { path }
      for k, v in pairs(case.opts) do
        local cur = config.opts.agenda[k]
        if type(v) == "table" and type(cur) == "table" and not vim.islist(v) then
          config.opts.agenda[k] = vim.tbl_deep_extend("force", cur, v)
        else
          config.opts.agenda[k] = v
        end
      end
      local st = view.state
      local saved = {}
      for _, k in ipairs({ "view", "anchor", "span", "log_mode", "inactive", "filters", "limits", "restrict" }) do
        saved[k] = st[k]
      end
      st.view = { blocks = case.blocks, multi = case.state.multi }
      st.anchor, st.span, st.restrict = nil, nil, nil
      st.log_mode = case.state.log_mode or false
      st.inactive = case.state.inactive or false
      st.filters = { tag = {}, category = {}, regexp = {}, effort = {} }
      st.limits = {}
      local ok, b = pcall(view.build, 80)
      for k, v in pairs(saved) do
        st[k] = v
      end
      ok = ok or error(b)
      eq(case.expected, b.lines)
    end)
  end
end)

